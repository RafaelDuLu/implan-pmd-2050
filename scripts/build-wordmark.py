"""Prepare original LEÓN 2050 paths from the local OFL Mona Sans font.
Run only when editing the wordmark; fonttools, brotli and skia-pathops are preparation-only dependencies.
"""
import json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib.removeOverlaps import removeOverlaps
ROOT=Path(__file__).resolve().parents[1]
font=TTFont(ROOT/'public/fonts/mona-sans.woff2')
font=instantiateVariableFont(font,{'wght':450},inplace=False)
cmap=font.getBestCmap()
removeOverlaps(font,glyphNames=[cmap[ord(c)] for c in set('LEÓN 2050')])
glyphset=font.getGlyphSet();em=font['head'].unitsPerEm
x=0;paths=[];bounds=[]
for char in 'LEÓN 2050':
 glyph=glyphset[cmap[ord(char)]]
 if char!=' ':
  pen=SVGPathPen(glyphset);bp=BoundsPen(glyphset)
  transform=(1,0,0,-1,x,0)
  glyph.draw(TransformPen(pen,transform));glyph.draw(TransformPen(bp,transform))
  paths.append(pen.getCommands());bounds.append(bp.bounds)
 x+=glyph.width-em*.065
left=min(b[0] for b in bounds)-12;top=min(b[1] for b in bounds)-12
right=max(b[2] for b in bounds)+12;bottom=max(b[3] for b in bounds)+12
viewbox=' '.join(str(round(n,3)) for n in (left,top,right-left,bottom-top))
(ROOT/'src/assets/leonWordmark.mjs').write_text('// Original lettering derived from local Mona Sans 450, SIL OFL. Generated by scripts/build-wordmark.py.\nexport const viewBox='+json.dumps(viewbox)+';\nexport const glyphs='+json.dumps(paths,separators=(',',':'))+';\n')
print('glyphs',len(paths),'viewBox',viewbox)
